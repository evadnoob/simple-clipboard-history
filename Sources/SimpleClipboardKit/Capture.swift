import AppKit
import CryptoKit

/// One pasteboard type and its bytes.
struct Representation: Equatable {
    var type: String
    var data: Data
}

/// Everything read from the pasteboard for one copy. A copy can hold several pasteboard items (for example several
/// files), and each item can hold several types of the same content.
struct CapturedClip: Equatable {
    var items: [[Representation]]
    var sourceAppName: String?
    var sourceBundleIdentifier: String?

    var byteSize: Int { items.reduce(0) { $0 + $1.reduce(0) { $0 + $1.data.count } } }

    /// Identifies identical copies, so copying the same thing twice keeps one clip.
    var contentHash: String {
        var hasher = SHA256()
        for item in items {
            hasher.update(data: Data("item\(item.count)\n".utf8))
            for representation in item {
                hasher.update(data: Data("\(representation.type)\n\(representation.data.count)\n".utf8))
                hasher.update(data: representation.data)
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    /// The full plain text, if any item has text. Used for search.
    var plainText: String? {
        let texts = items.compactMap { item -> String? in
            guard let representation = item.first(where: { $0.type == NSPasteboard.PasteboardType.string.rawValue })
            else { return nil }
            return String(data: representation.data, encoding: .utf8)
        }
        return texts.isEmpty ? nil : texts.joined(separator: "\n")
    }

    /// A short, single-line description for menus and lists.
    var preview: String {
        if let text = plainText {
            let collapsed = text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
            if !collapsed.isEmpty { return String(collapsed.prefix(200)) }
        }
        let fileNames = items.compactMap { item -> String? in
            guard let representation = item.first(where: { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }),
                  let text = String(data: representation.data, encoding: .utf8),
                  let url = URL(string: text) else { return nil }
            return url.lastPathComponent
        }
        if !fileNames.isEmpty { return fileNames.joined(separator: ", ") }
        let imageTypes: Set<String> = [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue,
                                       "public.jpeg", "public.heic"]
        if items.contains(where: { $0.contains(where: { imageTypes.contains($0.type) }) }) { return "Image" }
        return items.first?.first?.type ?? "Empty"
    }

    /// The kind shown in the menu: text, files, image or the first pasteboard type.
    var kind: String {
        if plainText != nil { return "text" }
        if items.contains(where: { $0.contains(where: { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }) }) {
            return items.count == 1 ? "file" : "\(items.count) files"
        }
        if preview == "Image" { return "image" }
        return items.first?.first?.type ?? "empty"
    }
}

/// Why a copy was not recorded.
enum SkipReason: Error, Equatable {
    case concealed
    case ignoredApp(String)
    case tooLarge(Int)
    case empty
    case paused
}

enum Capture {
    /// Markers from nspasteboard.org that password managers and similar apps put on copies that must not be kept.
    static let doNotRecordTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Checks the types before any data is read, so concealed content is never loaded.
    static func skipReason(types: [String], sourceBundleIdentifier: String?, settings: Settings) -> SkipReason? {
        if types.contains(where: doNotRecordTypes.contains) { return .concealed }
        if let identifier = sourceBundleIdentifier, settings.ignoredApps.contains(identifier) {
            return .ignoredApp(identifier)
        }
        if types.isEmpty { return .empty }
        return nil
    }

    /// Reads every item and type from the pasteboard. Stops and reports `.tooLarge` once the size passes the limit.
    static func read(_ pasteboard: NSPasteboard, sourceApp: NSRunningApplication?,
                     settings: Settings) -> Result<CapturedClip, SkipReason> {
        let allTypes = (pasteboard.pasteboardItems ?? []).flatMap { $0.types.map(\.rawValue) }
        if let reason = skipReason(types: allTypes, sourceBundleIdentifier: sourceApp?.bundleIdentifier,
                                   settings: settings) {
            return .failure(reason)
        }
        var items: [[Representation]] = []
        var total = 0
        for pasteboardItem in pasteboard.pasteboardItems ?? [] {
            var representations: [Representation] = []
            for type in pasteboardItem.types {
                guard let data = pasteboardItem.data(forType: type) else { continue }
                total += data.count
                if total > settings.maximumClipBytes { return .failure(.tooLarge(total)) }
                representations.append(Representation(type: type.rawValue, data: data))
            }
            if !representations.isEmpty { items.append(representations) }
        }
        if items.isEmpty { return .failure(.empty) }
        return .success(CapturedClip(items: items, sourceAppName: sourceApp?.localizedName,
                                     sourceBundleIdentifier: sourceApp?.bundleIdentifier))
    }

    /// Replaces the pasteboard contents with the stored items.
    static func write(_ items: [[Representation]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let pasteboardItems = items.map { representations -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for representation in representations {
                item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return item
        }
        pasteboard.writeObjects(pasteboardItems)
    }
}
